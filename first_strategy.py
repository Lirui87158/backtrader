
#以下是计算日成交量的代码示例：
import pandas as pd

def calculate_daily_volume(df, date_col='date', volume_col='volume'):
    """
    计算日成交量
    df: 包含日期和成交量的 DataFrame
    date_col: 日期列名
    volume_col: 成交量列名
    返回一个以日期为索引、每日成交量之和的 Series
    """
    df = df.copy()
    df[date_col] = pd.to_datetime(df[date_col])
    daily_volume = df.groupby(df[date_col].dt.date)[volume_col].sum()
    return daily_volume

# 示例用法
data = [
    {'date': '2026-04-25', 'volume': 1000},
    {'date': '2026-04-25', 'volume': 2000},
    {'date': '2026-04-26', 'volume': 1500},
]

df = pd.DataFrame(data)
print(calculate_daily_volume(df))



